/* ──────────────────────────────────────────────────────────────
   kontrolplane/feed — manage.js
   The manage page's own behaviour, and nothing else's: the filter
   box, the order control, and the clear button. app.js is owned
   elsewhere and knows nothing about this page.

   WHY A FILE AND NOT AN INLINE <script>
   script-src (internal/handler/middleware.go) is 'self' plus five
   pinned SHA-256 hashes. An inline block here would need a sixth
   hash regenerated by hand on every edit, and until someone did
   that the browser would refuse to run it — silently, because a
   blocked script logs to the console and nowhere else. A same-origin
   file satisfies 'self' and needs no maintenance.

   WHY IT BINDS THE WAY IT DOES
   /manage arrives through htmx (hx-target="#main"), so:
     · DOMContentLoaded has long since fired — there is nothing to
       wait for, the page initialises on execution;
     · every listener is delegated from `document`, registered once,
       so it survives the page being swapped out and back in (every
       cancel path re-renders the whole of #main);
     · htmx re-executes this file on each swap because the <script>
       tag rides inside the swapped markup, hence the guard below.

   The filter is deliberately client-side. There is no route for it,
   and adding one would mean a request per keystroke to re-render a
   list the browser already has. Everything it matches on is already
   in the DOM as data-* attributes.
   ────────────────────────────────────────────────────────────── */

(function () {
  'use strict';

  /* re-executed on every swap; the listeners below are global and
     must only ever be attached once */
  if (window.__feedManage) return;
  window.__feedManage = true;

  var UNFILED = '__unfiled__';

  /* The page is torn down and rebuilt by htmx on every cancel, so the
     two things the reader chose have to live outside it. Memory only:
     a filter is a transient narrowing of a list, not a preference, and
     a reload should honestly show everything. */
  var state = { filter: '', sort: 'folder' };

  /* Sorting needs the server's grouped order to be recoverable after
     the reader has sorted a-z. It is stamped onto each row as data-ord
     on first sight — but a row swapped out for its edit or confirm
     form arrives WITHOUT that attribute, so the value is also kept
     here against the row's (stable) id. Without this, opening the edit
     form on a row would move it to the end of the table. */
  var ordById = Object.create(null);

  function $(sel, root) {
    try { return (root || document).querySelector(sel); } catch (e) { return null; }
  }
  function page() { return $('.manage-page'); }
  function table() { var p = page(); return p ? $('.manage-table', p) : null; }
  function rowsOf(t) {
    if (!t || !t.tBodies || !t.tBodies[0]) return [];
    return Array.prototype.slice.call(t.tBodies[0].rows);
  }
  function isFeed(row) { return row.getAttribute('data-row') === 'feed'; }
  function attr(row, name) { return row.getAttribute(name) || ''; }

  function ordOf(row) {
    var own = row.getAttribute('data-ord');
    if (own !== null && own !== '') return Number(own);
    if (row.id && row.id in ordById) return ordById[row.id];
    return Number.MAX_SAFE_INTEGER;
  }

  /* Runs once per freshly rendered table. The server always emits the
     grouped order, so the DOM index at this moment IS the folder
     order — which is why it is captured before anything reorders. */
  function stamp(t) {
    rowsOf(t).forEach(function (row, i) {
      if (row.getAttribute('data-ord') === null) row.setAttribute('data-ord', String(i));
      if (row.id) ordById[row.id] = Number(row.getAttribute('data-ord'));
    });
    t.setAttribute('data-manage-ready', '1');
  }

  /* ══ ORDER ══
     Two orders, because they answer two different questions. "by
     folder" is the shape of your subscriptions and is what you want
     when you are tidying them. "a-z" ignores folders entirely and is
     what you want when you half-remember a name — it is the only way
     to find something in a sixty-feed list without knowing where you
     filed it. The folder heads are hidden by css in a-z mode rather
     than removed, so the order control is reversible without a
     server round-trip. */
  function applySort(t) {
    var body = t.tBodies && t.tBodies[0];
    if (!body) return;
    var rows = rowsOf(t);
    var ordered;

    if (state.sort === 'title') {
      var feeds = rows.filter(isFeed).sort(function (a, b) {
        var c = cmp(attr(a, 'data-title'), attr(b, 'data-title'));
        return c !== 0 ? c : ordOf(a) - ordOf(b);
      });
      var rest = rows.filter(function (r) { return !isFeed(r); })
                     .sort(function (a, b) { return ordOf(a) - ordOf(b); });
      /* the heads and the per-folder "no feeds here" rows are display:
         none in this mode; parking them after the feeds keeps the DOM
         order equal to the reading order */
      ordered = feeds.concat(rest);
    } else {
      ordered = rows.slice().sort(function (a, b) { return ordOf(a) - ordOf(b); });
    }

    /* one reflow rather than one per row */
    var frag = document.createDocumentFragment();
    ordered.forEach(function (row) { frag.appendChild(row); });
    body.appendChild(frag);
    t.setAttribute('data-sort', state.sort);
  }

  function cmp(a, b) {
    return String(a).toLowerCase().localeCompare(String(b).toLowerCase(), undefined, { numeric: true });
  }

  /* ══ FILTER ══
     Every space-separated term must match somewhere in the row, so
     "rust week" finds the weekly rust newsletter without caring which
     order the words fall in. Matching is against title + url + folder
     label, which is everything the row shows. */
  function applyFilter(t) {
    var terms = state.filter.toLowerCase().split(/\s+/).filter(Boolean);
    var filtering = terms.length > 0;
    var rows = rowsOf(t);

    /* which folder keys actually have a head row on this page. a feed
       whose folder was deleted carries a dangling id, so it is folded
       into the unfiled bucket the same way the server folds it. */
    var heads = Object.create(null);
    rows.forEach(function (row) {
      if (row.getAttribute('data-row') === 'group') heads[attr(row, 'data-folder')] = true;
    });

    var visible = Object.create(null);   /* matching feeds per folder */
    var held = Object.create(null);      /* every feed per folder     */
    var shown = 0;
    var total = 0;

    rows.forEach(function (row) {
      if (!isFeed(row)) return;
      total++;
      var key = attr(row, 'data-folder');
      if (!heads[key]) key = UNFILED;
      held[key] = (held[key] || 0) + 1;

      var hay = (attr(row, 'data-title') + ' ' + attr(row, 'data-url') + ' ' +
                 attr(row, 'data-folder-label')).toLowerCase();
      var ok = terms.every(function (term) { return hay.indexOf(term) !== -1; });
      row.hidden = !ok;
      if (!ok) return;
      shown++;
      visible[key] = (visible[key] || 0) + 1;
    });

    rows.forEach(function (row) {
      var kind = row.getAttribute('data-row');
      if (kind === 'group') {
        var key = attr(row, 'data-folder');
        /* an empty folder still shows its head when nothing is being
           filtered — that head is the only place it can be deleted */
        row.hidden = filtering && !visible[key];
        /* "3 feeds" over a single visible row is a lie about what you
           are looking at; under a filter the head counts the rows the
           reader can actually see */
        swap(row.querySelector('.manage-group-count'), filtering
          ? (visible[key] || 0) + ' of ' + (held[key] || 0)
          : null);
      } else if (kind === 'empty') {
        row.hidden = filtering;
      } else if (kind === 'nomatch') {
        row.hidden = !(filtering && shown === 0);
      }
    });

    report(shown, total, filtering);
  }

  /* Replaces an element's text with `next`, remembering what the
     server wrote so passing null puts it back. Used by every count on
     the page, so none of them has to be re-rendered to recover. */
  function swap(el, next) {
    if (!el) return;
    if (!el.getAttribute('data-base')) {
      el.setAttribute('data-base', el.textContent.replace(/\s+/g, ' ').trim());
    }
    el.textContent = next === null ? el.getAttribute('data-base') : next;
  }

  /* The inventory line doubles as the filter's result count. It is
     aria-live, so a screen reader hears "showing 3 of 42 feeds"
     instead of watching rows vanish in silence. */
  function report(shown, total, filtering) {
    swap($('.manage-count', page()), filtering
      ? 'showing ' + shown + ' of ' + total + ' ' + (total === 1 ? 'feed' : 'feeds')
      : null);
  }

  function syncSortButtons() {
    var p = page();
    if (!p) return;
    var btns = p.querySelectorAll('[data-manage-sort]');
    Array.prototype.forEach.call(btns, function (b) {
      b.setAttribute('aria-pressed', b.getAttribute('data-manage-sort') === state.sort ? 'true' : 'false');
    });
  }

  /* ══ BOOT ══
     Called on execution and after every htmx swap anywhere in the
     app. It does its work exactly once per rendered table, and is
     otherwise a no-op — including for the swaps that replace a single
     row with its edit or confirm form. That restraint is deliberate,
     and it is two bug fixes:

       · re-sorting would re-parent every <tr>, which drops focus —
         and the row that just arrived is the edit form whose first
         field has autofocus, or the confirm whose cancel does;
       · re-filtering would hide that row whenever the active filter
         term matched something the fragment cannot carry (the
         confirm fragment is handed a store.Feed and has no folder
         label to match on). Clicking "remove" under a filter would
         make the question vanish.

     Neither is needed: a row can only be swapped if it was on screen
     and matching in the first place, and it replaces itself in
     place, so both the order and the visibility are already right. */
  function boot() {
    var t = table();
    if (!t || t.getAttribute('data-manage-ready') === '1') return;
    stamp(t);
    /* the page is rebuilt from scratch on every cancel; put the
       reader's filter text and chosen order back on it */
    var input = $('.manage-filter-input', page());
    if (input && input.value !== state.filter) input.value = state.filter;
    syncSortButtons();
    applySort(t);
    applyFilter(t);
  }

  function refresh() {
    var t = table();
    if (t) applyFilter(t);
  }

  /* ══ LISTENERS — registered once, delegated from document ══ */

  document.addEventListener('input', function (e) {
    var el = e.target;
    if (!el || !el.classList || !el.classList.contains('manage-filter-input')) return;
    state.filter = el.value;
    refresh();
  });

  document.addEventListener('click', function (e) {
    var el = e.target;
    if (!el || !el.closest) return;

    var sort = el.closest('[data-manage-sort]');
    if (sort) {
      state.sort = sort.getAttribute('data-manage-sort') === 'title' ? 'title' : 'folder';
      syncSortButtons();
      var t = table();
      if (t) { applySort(t); applyFilter(t); }
      return;
    }

    if (el.closest('.manage-filter-clear')) {
      var input = $('.manage-filter-input', page());
      if (!input) return;
      input.value = '';
      state.filter = '';
      refresh();
      input.focus();
    }
  });

  /* Escape clears the filter before app.js gets the chance to blur the
     field — capture phase, and only while there is something to
     clear, so an empty box still blurs the way every other field in
     the app does. */
  document.addEventListener('keydown', function (e) {
    if (e.key !== 'Escape') return;
    var el = e.target;
    if (!el || !el.classList || !el.classList.contains('manage-filter-input')) return;
    if (el.value === '') return;
    e.preventDefault();
    e.stopPropagation();
    el.value = '';
    state.filter = '';
    refresh();
  }, true);

  document.addEventListener('htmx:load', boot);
  document.addEventListener('htmx:afterSwap', boot);

  boot();
})();
